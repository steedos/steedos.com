#!/usr/bin/env node
/**
 * Turn redirects.json (the Next.js `redirects()` format the old site used)
 * into nginx rules, so old URLs keep answering with a real 301.
 *
 * - `:param` matches one segment, `:param*` zero or more (Next semantics).
 * - Rules are matched in file order, first match wins (as in Next).
 * - Chains are flattened: /customers -> /customer-success-stories ->
 *   /resources/customer-success-stories becomes one hop.
 *
 * Writes .nginx/redirects.conf (included by docker/nginx.conf). Also exports
 * resolveRedirect() for scripts/verify-urls.mjs.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RULES = JSON.parse(fs.readFileSync(path.join(ROOT, 'redirects.json'), 'utf8'));

function compile(rule) {
  const names = [];
  const pattern = rule.source
    .split('/')
    .map((seg) => {
      const m = seg.match(/^:(\w+)(\*)?$/);
      if (!m) return seg.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      names.push(m[1]);
      return m[2] ? '(?:/(.*))?' : '/([^/]+)';
    })
    .join('/')
    // "/x//([^/]+)" -> "/x/([^/]+)": the segment regexes carry their own slash
    .replace(/\/(\(\?:\/|\/\()/g, '$1');
  return { ...rule, names, pattern, regex: new RegExp(`^${pattern}/?$`) };
}

const compiled = RULES.map(compile);
const isLiteral = (r) => r.names.length === 0;

function applyRule(rule, pathname) {
  const m = pathname.match(rule.regex);
  if (!m) return null;
  return rule.names.reduce((dest, name, i) => dest.replace(`:${name}*`, m[i + 1] ?? '').replace(`:${name}`, m[i + 1] ?? ''), rule.destination);
}

/** Final destination for a path after following every redirect, or null. */
export function resolveRedirect(pathname) {
  let current = pathname;
  let hit = false;
  for (let hops = 0; hops < 10; hops++) {
    if (!current.startsWith('/')) break; // external
    const target = compiled.map((r) => applyRule(r, current)).find((d) => d !== null);
    if (target == null) break;
    hit = true;
    // Internal targets lose their trailing slash (the site serves /a, not /a/).
    current = target.startsWith('/') && target.length > 1 ? target.replace(/\/$/, '') : target;
  }
  return hit ? current : null;
}

function nginxRules() {
  const lines = ['# Generated by scripts/gen-nginx-redirects.mjs from redirects.json. Do not edit.'];
  const seen = new Set();
  for (const rule of compiled) {
    if (isLiteral(rule)) {
      if (seen.has(rule.source)) continue; // first match wins, as in Next
      seen.add(rule.source);
      lines.push(`location = ${rule.source} { return 301 ${resolveRedirect(rule.source)}; }`);
    } else {
      // Captures can't be pre-resolved; follow-ups only matter for literals here.
      let n = 0;
      const dest = rule.names.reduce((d, name) => d.replace(new RegExp(`:${name}\\*?`), `$${++n}`), rule.destination);
      lines.push(`location ~ "^${rule.pattern}$" { return 301 ${dest}; }`);
    }
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = path.join(ROOT, '.nginx', 'redirects.conf');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, nginxRules());
  console.log(`Wrote ${path.relative(ROOT, out)} (${compiled.length} rules)`);
}
